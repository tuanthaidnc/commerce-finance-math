import {execFileSync} from 'node:child_process';
import {mkdtempSync,mkdirSync,writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';
if(!process.env.npm_execpath) throw new Error('Run npm run check:package');
const root=fileURLToPath(new URL('../',import.meta.url));
const temporary=mkdtempSync(join(tmpdir(),'oss-consumer-'));
const consumer=join(temporary,'consumer'); mkdirSync(consumer);
const npm=(args,cwd)=>execFileSync(process.execPath,[process.env.npm_execpath,...args],{cwd,encoding:'utf8',stdio:['ignore','pipe','pipe']});
const [packed]=JSON.parse(npm(['pack','--json','--pack-destination',temporary],root));
const names=new Set(packed.files.map(f=>f.path));
for(const f of ['index.js','index.d.ts','README.md','LICENSE']) if(!names.has(f)) throw new Error('Missing '+f);
writeFileSync(join(consumer,'package.json'),JSON.stringify({private:true,type:'module'}));
npm(['install','--ignore-scripts','--no-audit','--no-fund',join(temporary,packed.filename)],consumer);
console.log(execFileSync(process.execPath,['--input-type=module','--eval',`import assert from 'node:assert/strict'; import * as api from 'commerce-finance-math'; assert.equal(api.blendedRoas([{netRevenueMinor:10000,adsMinor:5000}]).value,2); console.log('Installed consumer PASS');`],{cwd:consumer,encoding:'utf8'}).trim());
